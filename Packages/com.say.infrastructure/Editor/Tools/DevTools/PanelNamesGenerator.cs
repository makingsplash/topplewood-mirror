using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

using UnityEditor;
using UnityEditor.AddressableAssets;
using UnityEditor.AddressableAssets.Settings;

using UnityEngine;

namespace SGS.Editor.Tools.DevTools
{
#if !GPIE_DISABLE_PANEL_NAMES_GENERATOR
    public static class PanelNamesGenerator
    {
        [MenuItem("Utils/Generate Ui Panels Constants")]
        public static void GenerateConstants()
        {
            GenerateNames("3DUi", "WorldPanels");
            GenerateNames("Screens", "ScreenNames");
            GenerateNames("Subpanels", "Subpanels");
            AssetDatabase.Refresh();
        }

        private static void GenerateNames(string subdirName, string className)
        {
            const string header = @"// Generated by PanelNamesGenerator, don't change
namespace Ui
{";
            const string footer = @"    }
}";

            StringBuilder text = new StringBuilder();

            text.AppendLine(header);
            text.AppendFormat("    public static class {0}\n", className);
            text.AppendLine("    {");

            AddressableAssetGroup group = GetPoolAddressableGroup();
            List<AddressableAssetEntry> assetEntries = new();
            group.GatherAllAssets(assetEntries, false, true, true);
            foreach (AddressableAssetEntry assetEntry in assetEntries)
            {
                if (assetEntry.IsFolder)
                {
                    continue;
                }

                if (string.IsNullOrEmpty(assetEntry.AssetPath))
                {
                    continue;
                }

                
                var assetDir = Path.GetDirectoryName(assetEntry.AssetPath);
                if (!assetDir.EndsWith(subdirName, true, CultureInfo.InvariantCulture))
                {
                    continue;
                }
                text.AppendFormat($"        public const string {assetEntry.MainAsset.name} = \"{assetEntry.address}\";\n");
            }
            
            text.Append(footer);
            
            File.WriteAllText(Path.Combine(Application.dataPath, $"Scripts/Ui/{className}.cs"), text.ToString());
        }
        
        private static AddressableAssetGroup GetPoolAddressableGroup()
        {
            var setting = AddressableAssetSettingsDefaultObject.Settings;
            if (setting!=null)
            {
                AddressableAssetGroup group = setting.FindGroup("UI");
                return group;
            }

            return null;
        }
    }
    
    public class UiPrefabsAssetModificationProcessor : UnityEditor.AssetModificationProcessor
    {
        private static string[] OnWillSaveAssets(string[] paths)
        {
            foreach (string path in paths)
            {
                if (CheckAsset(path))
                {
                    PanelNamesGenerator.GenerateConstants();
                    break;
                }
            }

            return paths;
        }

        private static bool CheckAsset(string assetPath)
        {
            if (assetPath.Contains("Assets/Prefabs/Ui") && Path.GetExtension(assetPath) == ".prefab")
            {
                return true;
            }

            return false;
        }
    }
#endif // GPIE_DISABLE_PANEL_NAMES_GENERATOR
}
